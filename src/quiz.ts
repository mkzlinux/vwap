export function questionsFor(opts: { seriesId?: string; workId?: string; n?: number }): QuizQuestion[] {
  const { seriesId, workId, n = 8 } = opts;
  let pool = questions;
  if (workId) {
    const hit = questions.filter((q) => q.workId === workId);
    if (hit.length >= 3) pool = hit;
    else pool = questions.filter((q) => q.seriesId === seriesId || q.workId === workId);
  } else if (seriesId) {
    const hit = questions.filter((q) => q.seriesId === seriesId);
    pool = hit.length >= 4 ? hit : questions;
  }
  const copy = [...pool].sort(() => Math.random() - 0.5);
  return copy.slice(0, Math.min(n, copy.length));
}

